export function programById(id: string): LoyaltyProgram | undefined {
  return LOYALTY_PROGRAMS.find((p) => p.id === id);
}

/** Airline/hotel programs a bank currency transfers to. */
export function partnersFrom(bankProgramId: string): TransferPartner[] {
  return TRANSFER_PARTNERS.filter((t) => t.from === bankProgramId);
}

/** Bank currencies that transfer into an airline/hotel program. */
export function partnersTo(programId: string): TransferPartner[] {
  return TRANSFER_PARTNERS.filter((t) => t.to === programId);
}
